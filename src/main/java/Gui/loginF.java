    private void LoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_LoginActionPerformed
        String username = masukuser.getText().trim();
        String password = masukpw.getText().trim();
        
        if(username.isEmpty() || password.isEmpty()){
            JOptionPane.showMessageDialog(this, "Username dan Password harus diisi.",
                                          "peringatan", JOptionPane.INFORMATION_MESSAGE);
            return;
        }
        
        if (username.equals("admin") && password.equals("admin123")){
            JOptionPane.showMessageDialog(this, "Login berhasil sebagai Admin", 
                                          "Sukses", JOptionPane.INFORMATION_MESSAGE);
            
            admin Admin = new admin();
            Admin.setVisible(true);
            this.dispose();
        } else if(username.equals("kasir") && password.equals("kasir123")){
            JOptionPane.showMessageDialog(this, "Login berhasil sebagai kasir",
                                            "Sukses" , JOptionPane.INFORMATION_MESSAGE);
        
            kasir Kasir = new kasir();
            Kasir.setVisible(true);
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Username atau password salah.",
                                           "Login Gagal", JOptionPane.ERROR_MESSAGE);
            masukpw.setText(" ");
        }
    }//GEN-LAST:event_LoginActionPerformed

