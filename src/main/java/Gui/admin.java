    private void setupTabelProduk() {
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn("ID");
        model.addColumn("Nama Produk");
        model.addColumn("Stok");
        model.addColumn("Harga");
        model.addColumn("Kategori");
        tabelProduk.setModel(model);
    }

    private void refreshTabelProduk() {
        DefaultTableModel model = (DefaultTableModel) tabelProduk.getModel();
        model.setRowCount(0);
        
        for (Produk p : produkService.daftarProduk){
            model.addRow(new Object[]{
                p.getIdproduk(), p.getNamaProduk(), p.getStok(), p.getHarga()
            });
        }
    }
