    private void tambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tambahActionPerformed
        String nama = NamaProduk.getText().trim();
        String stokStr = Stok.getText().trim();
        String hargaStr = Harga.getText().trim();

    if (nama.isEmpty() || stokStr.isEmpty() || hargaStr.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Semua field harus diisi.",
                "Peringatan", JOptionPane.WARNING_MESSAGE);
        return;
    }

    int stok;
    double harga;

    try {
        stok = Integer.parseInt(stokStr);
    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this,
                "Stok harus berupa bilangan bulat (contoh: 10).",
                "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    try {
        harga = Double.parseDouble(hargaStr);
    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this,
                "Harga harus berupa angka (contoh: 15000 atau 15000.50).",
                "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    if (stok < 0) {
        JOptionPane.showMessageDialog(this,
                "Stok tidak boleh bernilai negatif.",
                "Peringatan", JOptionPane.WARNING_MESSAGE);
        return;
    }

    if (harga < 0) {
        JOptionPane.showMessageDialog(this,
                "Harga tidak boleh bernilai negatif.",
                "Peringatan", JOptionPane.WARNING_MESSAGE);
        return;
    }

    produkService.tambahProdukGUI(nama, stok, harga);
    refreshTabelProduk();
    bersihActionPerformed(evt);

    JOptionPane.showMessageDialog(this,
            "Produk berhasil ditambahkan.",
            "Sukses", JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_tambahActionPerformed

    private void ubahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ubahActionPerformed
        int row = tabelProduk.getSelectedRow();
    if (row < 0) {
        JOptionPane.showMessageDialog(this,
                "Pilih dulu produk di tabel yang ingin diubah.",
                "Peringatan", JOptionPane.WARNING_MESSAGE);
        return;
    }

    int id = (int) tabelProduk.getValueAt(row, 0);
    String nama = NamaProduk.getText().trim();
    String stokStr = Stok.getText().trim();
    String hargaStr = Harga.getText().trim();

    if (nama.isEmpty() || stokStr.isEmpty() || hargaStr.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Semua field harus diisi.",
                "Peringatan", JOptionPane.WARNING_MESSAGE);
        return;
    }

    int stok;
    double harga;

    try {
        stok = Integer.parseInt(stokStr);
    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this,
                "Stok harus berupa bilangan bulat (contoh: 10).",
                "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    try {
        harga = Double.parseDouble(hargaStr);
    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this,
                "Harga harus berupa angka (contoh: 15000 atau 15000.50).",
                "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    if (stok < 0) {
        JOptionPane.showMessageDialog(this,
                "Stok tidak boleh bernilai negatif.",
                "Peringatan", JOptionPane.WARNING_MESSAGE);
        return;
    }

    if (harga < 0) {
        JOptionPane.showMessageDialog(this,
                "Harga tidak boleh bernilai negatif.",
                "Peringatan", JOptionPane.WARNING_MESSAGE);
        return;
    }

    boolean berhasil = produkService.ubahProdukGUI(id, nama, stok, harga);
    refreshTabelProduk();
        bersihActionPerformed(evt);

    if (berhasil) {
        JOptionPane.showMessageDialog(this,
                "Produk berhasil diperbarui.",
                "Sukses", JOptionPane.INFORMATION_MESSAGE);
    } else {
        JOptionPane.showMessageDialog(this,
                "Produk tidak ditemukan.",
                "Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_ubahActionPerformed

    private void hapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_hapusActionPerformed
        int row = tabelProduk.getSelectedRow();
    if (row < 0) {
        JOptionPane.showMessageDialog(this,
                "Pilih dulu produk di tabel yang ingin dihapus.",
                "Peringatan", JOptionPane.WARNING_MESSAGE);
        return;
    }

    int id = (int) tabelProduk.getValueAt(row, 0);
    String namaProduk = (String) tabelProduk.getValueAt(row, 1);

    int konfirmasi = JOptionPane.showConfirmDialog(this,
            "Yakin ingin menghapus produk \"" + namaProduk + "\"?",
            "Konfirmasi Hapus", JOptionPane.YES_NO_OPTION);

    if (konfirmasi == JOptionPane.YES_OPTION) {
        produkService.hapusProdukGUI(id);
        refreshTabelProduk();
        bersihActionPerformed(evt);

        JOptionPane.showMessageDialog(this,
                "Produk berhasil dihapus.",
                "Sukses", JOptionPane.INFORMATION_MESSAGE);
    }
    }//GEN-LAST:event_hapusActionPerformed

