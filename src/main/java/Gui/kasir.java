    private void TambahkeraActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_TambahkeraActionPerformed
        int row = tabelPro.getSelectedRow();
        if (row < 0) {
            JOptionPane.showMessageDialog(this, "Pilih dulu produk dari tabel.",
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String jumlahStr = JUMLAH.getText().trim();  // ganti sesuai nama field Jumlah kamu
        if (jumlahStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Masukkan jumlah produk.",
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            int idProduk = (int) tabelPro.getValueAt(row, 0);
            int jumlahBeli = Integer.parseInt(jumlahStr);

            String hasil = pesananService.tambahPesananGUI(idProduk, jumlahBeli, produkService);
            boolean berhasil = hasil.startsWith(" ");

            JOptionPane.showMessageDialog(this, hasil,
                    berhasil ? "Sukses" : "Gagal",
                    berhasil ? JOptionPane.INFORMATION_MESSAGE : JOptionPane.WARNING_MESSAGE);

            if (berhasil) {
                JUMLAH.setText("");
                refreshTabelKeranjang();
            }
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Jumlah harus berupa angka.",
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_TambahkeraActionPerformed

    private void pesanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_pesanActionPerformed
         if (pesananService.daftarPesanan.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Keranjang masih kosong.",
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }
        String[] pilihanMetode = {"Tunai", "Debit", "QRIS"};
        String metodeBayar = (String) JOptionPane.showInputDialog(this,
                "Pilih metode pembayaran:", "Metode Pembayaran",
                JOptionPane.PLAIN_MESSAGE, null, pilihanMetode, pilihanMetode[0]);

        if (metodeBayar == null) return; 

    

        double total = pesananService.hitungTotal();

        String input = JOptionPane.showInputDialog(this,
                String.format("Metode: %s%nTotal belanja: Rp%.2f%nMasukkan uang bayar:", metodeBayar, total),
                "Checkout", JOptionPane.PLAIN_MESSAGE);

        if (input == null) return;

        double uangBayar;
        try {
            uangBayar = Double.parseDouble(input.trim());
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Input uang bayar tidak valid.",
                    "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        Pembayaran pembayaran;
        try {
            pembayaran = new Pembayaran(total, uangBayar);
        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(),
                    "Pembayaran Gagal", JOptionPane.ERROR_MESSAGE);
            return;
        }

        for (Pesanan p : pesananService.daftarPesanan) {
            p.getProduk().kurangiStok(p.getJumlah());
            transaksiService.tambahTransaksi(
                    new Transaksi(p.getProduk().getNamaProduk(), p.getJumlah(), p.getSubtotal())
            );
        }

        StringBuilder sb = new StringBuilder();
        sb.append("Total Bayar : Rp").append(String.format("%.2f", pembayaran.getTotalBayar())).append("\n");
        sb.append("Uang Bayar  : Rp").append(String.format("%.2f", pembayaran.getUangBayar())).append("\n");
        sb.append("Kembalian   : Rp").append(String.format("%.2f", pembayaran.getKembalian()));
        JOptionPane.showMessageDialog(this, sb.toString(), "Struk Pembayaran",
                JOptionPane.INFORMATION_MESSAGE);

        pesananService.kosongkan();
        refreshTabelProduk();
        refreshTabelKeranjang();
    }//GEN-LAST:event_pesanActionPerformed

    private void transaksiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_transaksiActionPerformed
        if (transaksiService.daftarTransaksi.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Belum ada transaksi.",
                "Riwayat Transaksi", JOptionPane.INFORMATION_MESSAGE);
        return;
    }

        StringBuilder sb = new StringBuilder();
        sb.append(String.format("%-20s %-8s %-12s%n", "Nama Produk", "Jumlah", "Total"));
        sb.append("--------------------------------------------\n");

        double grandTotal = 0;
        for (Transaksi t : transaksiService.daftarTransaksi) {
            sb.append(String.format("%-20s %-8d Rp%.2f%n",
                    t.getNamaProduk(), t.getJumlah(), t.getTotal()));
            grandTotal += t.getTotal();
        }

        sb.append("--------------------------------------------\n");
        sb.append(String.format("Grand Total: Rp%.2f", grandTotal));

        JTextArea textArea = new JTextArea(sb.toString());
        textArea.setEditable(false);
        textArea.setFont(new java.awt.Font("Monospaced", java.awt.Font.PLAIN, 13));

        JScrollPane scrollPane = new JScrollPane(textArea);
        scrollPane.setPreferredSize(new java.awt.Dimension(400, 300));

        JOptionPane.showMessageDialog(this, scrollPane,
                "Riwayat Transaksi", JOptionPane.PLAIN_MESSAGE);
    }//GEN-LAST:event_transaksiActionPerformed

    private void HAPUSActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_HAPUSActionPerformed
        int row = daftarmenu.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Pilih dulu pesanan yang mau dihapus.",
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int konfirmasi = JOptionPane.showConfirmDialog(this,
                "Hapus pesanan ini dari keranjang?", "Konfirmasi",
                JOptionPane.YES_NO_OPTION);
        if (konfirmasi != JOptionPane.YES_OPTION) return;

        boolean berhasil = pesananService.hapusPesanan(row + 1); 
        if (berhasil) {
            refreshTabelKeranjang();
        } else {
            JOptionPane.showMessageDialog(this, "Gagal menghapus pesanan.",
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_HAPUSActionPerformed

    private void UBAHActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_UBAHActionPerformed
        int row = daftarmenu.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Pilih dulu pesanan yang mau diubah.",
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String input = JOptionPane.showInputDialog(this, "Masukkan jumlah baru:",
                "Ubah Pesanan", JOptionPane.PLAIN_MESSAGE);
        if (input == null) return;

        int jumlahBaru;
        try {
            jumlahBaru = Integer.parseInt(input.trim());
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Jumlah harus berupa angka.",
                    "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        String hasil = pesananService.ubahJumlahPesanan(row + 1, jumlahBaru);
        JOptionPane.showMessageDialog(this, hasil);
        refreshTabelKeranjang();
    }//GEN-LAST:event_UBAHActionPerformed

