    private void refreshTabelProduk() {
        DefaultTableModel model = (DefaultTableModel) tabelPro.getModel();
               model.setRowCount(0);
               for (Produk p : produkService.daftarProduk) {
                   model.addRow(new Object[]{
                       p.getIdproduk(), p.getNamaProduk(), p.getStok(), p.getHarga()
                   });
        } 
    }

    private void refreshTabelKeranjang() {
        DefaultTableModel model = (DefaultTableModel) daftarmenu.getModel();
                model.setRowCount(0);
                for (Pesanan p : pesananService.daftarPesanan) {
                    model.addRow(new Object[]{
                        p.getProduk().getIdproduk(),
                        p.getProduk().getNamaProduk(),
                        p.getJumlah(),
                        p.getSubtotal()
                    });
                }
                total.setText(String.format("Total: Rp%.2f", pesananService.hitungTotal())); 
    }
